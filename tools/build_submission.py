"""Export the maintained matcher to the teacher's self-contained v2 submission."""

import argparse
import ast
import json
from pathlib import Path
import re
import shlex
from textwrap import indent

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "address_segmentation"
TEMPLATE = ROOT / "teacher-info" / "GettingStarted_v2.ipynb"
MODULES = ("normalize", "model", "catalog", "retrieve", "verify", "select",
           "approximate", "typing", "trie", "matcher")
BACKENDS = ("indexed", "trie_dp")
DEVELOPMENT_ONLY = {"is_base_alnum", "validate_field_sequence", "osa_distance_reference",
                    "osa_distance", "is_house_number_token"}
API = '''    def __init__(
        self,
        list_province: list[str],
        list_ward: list[str],
        list_street: list[str],
    ):
        self._matcher = self.AddressMatcher(
            streets=list_street, wards=list_ward, provinces=list_province,
            config=self.MatcherConfig(backend={backend!r}),
        )

    def process(self, s: str):
        return self._matcher.identify(s)
'''


def declaration_name(node):
    if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
        return node.name
    if isinstance(node, ast.Assign) and len(node.targets) == 1:
        target = node.targets[0]
    elif isinstance(node, ast.AnnAssign):
        target = node.target
    else:
        raise ValueError(f"Unsupported matcher declaration: {ast.dump(node)}")
    if not isinstance(target, ast.Name):
        raise ValueError(f"Unsupported matcher assignment: {ast.dump(node)}")
    return target.id


class SolutionScope(ast.NodeTransformer):
    """Move module globals into Solution and qualify their runtime references."""

    def __init__(self, names):
        self.names = names
        self.in_function = False

    def annotation(self, node):
        # The enclosing class is still being defined when it creates the
        # nested classes. Postpone their references to other nested types.
        if node is not None and any(
            isinstance(ref, ast.Name) and ref.id in self.names for ref in ast.walk(node)
        ):
            return ast.Constant(ast.unparse(node))
        return node

    def visit_FunctionDef(self, node):
        node.returns = self.annotation(node.returns)
        node.args = self.visit(node.args)
        was_in_function = self.in_function
        self.in_function = True
        node.body = [self.visit(statement) for statement in node.body]
        self.in_function = was_in_function
        return node

    def visit_arg(self, node):
        node.annotation = self.annotation(node.annotation)
        return node

    def visit_AnnAssign(self, node):
        node.annotation = self.annotation(node.annotation)
        if node.value is not None:
            node.value = self.visit(node.value)
        return node

    def visit_Name(self, node):
        if self.in_function and node.id in self.names:
            return ast.Attribute(ast.Name("Solution", ast.Load()), node.id, node.ctx)
        return node


def binding(node):
    if isinstance(node, ast.Name) and isinstance(node.ctx, (ast.Store, ast.Del)):
        return node.id
    if isinstance(node, ast.arg):
        return node.arg
    if isinstance(node, (ast.FunctionDef, ast.ClassDef, ast.ExceptHandler)):
        return node.name
    return None


def matching_source(backend="indexed"):
    if backend not in BACKENDS:
        raise ValueError(f"Unsupported backend: {backend!r}")
    imports, modules, names = {}, {}, set()
    for module in MODULES:
        tree = ast.parse((PACKAGE / f"{module}.py").read_text(encoding="utf-8"))
        declarations = []
        for node in tree.body:
            if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
                continue
            if isinstance(node, ast.If) and isinstance(node.test, ast.Name) and node.test.id == "TYPE_CHECKING":
                continue
            if isinstance(node, (ast.Import, ast.ImportFrom)):
                if not isinstance(node, ast.ImportFrom) or not node.module.startswith("address_segmentation"):
                    node.names = [alias for alias in node.names if alias.name != "TYPE_CHECKING"]
                    if node.names:
                        imports[ast.unparse(node)] = None
                continue
            name = declaration_name(node)
            if name in DEVELOPMENT_ONLY:
                continue
            if name in names:
                raise ValueError(f"Duplicate matcher declaration: {name}")
            names.add(name)
            declarations.append(node)
        modules[module] = declarations

    scope = SolutionScope(names)
    chunks = ["# Generated by tools.build_submission from the maintained matcher.\nclass Solution:",
              API.format(backend=backend)]
    for module, declarations in modules.items():
        blocks = []
        for node in declarations:
            if isinstance(node, ast.ClassDef) and node.name == "AddressMatcher":
                node.body = [item for item in node.body
                             if not isinstance(item, ast.FunctionDef) or item.name != "identify_with_trace"]
            # This exporter qualifies only module globals. Fail on shadowing
            # instead of silently changing the meaning of a local binding.
            descendants = (child for child in ast.walk(node) if child is not node)
            shadowed = names.intersection(binding(child) for child in descendants)
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                shadowed.discard(declaration_name(node))
            if shadowed:
                raise ValueError(f"Matcher local bindings shadow exported names: {sorted(shadowed)}")
            node = scope.visit(node)
            if isinstance(node, ast.FunctionDef):
                node.decorator_list.insert(0, ast.Name("staticmethod", ast.Load()))
            blocks.append(ast.unparse(ast.fix_missing_locations(node)))
        chunks.append(f"    # {module}.py\n" + indent("\n\n".join(blocks), "    "))
    imports_source = "\n".join(imports) + "\n"
    solution_source = "\n\n".join(chunks) + "\n"
    compile(imports_source + solution_source, "<teacher v2 source>", "exec")
    return imports_source, solution_source


def code(cell):
    return "".join(cell["source"])


def python_grader(cells):
    """Keep grading behind a main guard and translate notebook shell lines."""
    lines = ["if __name__ == '__main__':", "    import subprocess", "    import sys", ""]
    for cell in cells:
        for line in code(cell).splitlines():
            if line.lstrip().startswith("!"):
                command, *args = shlex.split(line.lstrip()[1:])
                command_args = repr([command, *args])
                if command == "pip":
                    command_args = f"[sys.executable, '-m', 'pip', *{args!r}]"
                prefix = line[:len(line) - len(line.lstrip())]
                line = f"{prefix}subprocess.run({command_args}, check=True)"
            lines.append("    " + line if line else "")
        lines.append("")
    return "\n".join(lines)


def build_submission(team_name, output_dir, template=TEMPLATE, *, backend="indexed"):
    if not re.fullmatch(r"Group_(?:[0-9]+|xx)", team_name):
        raise ValueError("Use Group_ followed by the assigned digits, or Group_xx for a draft")
    notebook = json.loads(Path(template).read_text(encoding="utf-8"))
    cells = notebook["cells"]
    if len(cells) != 7 or any(cell["cell_type"] != "code" for cell in cells):
        raise ValueError("Expected the teacher v2 template with seven code cells")
    imports, solution = matching_source(backend)
    team_comment = "# Draft placeholder. Rebuild with the assigned team name.\n" if team_name == "Group_xx" else ""
    student_cells = (
        f"{team_comment}TEAM_NAME = {team_name!r}\n",
        "# The matcher uses the three inventories provided by the grader.\n",
        "# The matcher uses only Python standard-library modules.\n",
        imports,
        solution,
    )
    for cell, source in zip(cells, student_cells):
        cell["source"] = source.splitlines(keepends=True)
    for cell in cells:
        cell["execution_count"] = None
        cell["outputs"] = []
        for key in ("colab", "outputId", "executionInfo"):
            cell["metadata"].pop(key, None)

    python = "\n\n".join((*student_cells, python_grader(cells[-2:])))
    compile(python, f"{team_name}.py", "exec")
    target = Path(output_dir) / team_name
    target.mkdir(parents=True, exist_ok=True)
    script = target / f"{team_name}.py"
    script.write_text(python, encoding="utf-8")
    (target / f"{team_name}.ipynb").write_text(
        json.dumps(notebook, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
    )
    return script


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--group", required=True, help="Assigned team name, e.g. Group_07")
    parser.add_argument("--output-dir", type=Path, default=Path("."))
    parser.add_argument("--template", type=Path, default=TEMPLATE)
    parser.add_argument("--backend", choices=BACKENDS, default="indexed")
    args = parser.parse_args()
    print(build_submission(args.group, args.output_dir, args.template, backend=args.backend).parent)


if __name__ == "__main__":
    main()
